import assert from 'node:assert/strict';
import http from 'node:http';
import {once} from 'node:events';
import express from 'express';
import {Hono} from 'hono';
import {init, flush, shutdown} from '@everock/sdk/node';
import {requestHandler, errorHandler} from '@everock/sdk/express';
import {honoMiddleware, svelteKitHandle, astroMiddleware} from '@everock/sdk/frameworks';
import * as edge from '@everock/sdk/edge';
import {honoMiddleware as edgeHono} from '@everock/sdk/frameworks/edge';
const received = [];
const collector = http.createServer(async (req,res) => {let text=''; for await(const data of req)text+=data; received.push(...JSON.parse(text).events); res.end('{}');});
collector.listen(0,'127.0.0.1'); await once(collector,'listening');
const endpoint=`http://127.0.0.1:${collector.address().port}`;
const clientFetch = globalThis.fetch.bind(globalThis);
init({publicKey:'pk_fixture',endpoint,persistence:false,flushIntervalMs:60000,component:'api'});
const app=express(); app.use(requestHandler());
app.get('/items/:slug', (req,res) => res.status(201).json({slug:req.params.slug}));
app.get('/fail/:slug', () => {throw new Error('original failure');});
app.use(errorHandler()); app.use((error,req,res,next) => res.status(500).send(error.message));
const server=app.listen(0,'127.0.0.1'); await once(server,'listening');
try {
  const origin=`http://127.0.0.1:${server.address().port}`;
  const result=await clientFetch(origin+'/items/anything?token=fixture_secret'); assert.equal(result.status,201);
  assert.deepEqual(await result.json(),{slug:'anything'});
  assert.equal(await (await clientFetch(origin+'/fail/anything')).text(),'original failure');
  const hono=new Hono(); hono.use('*',honoMiddleware());
  hono.get('/things/:slug',c=>c.text('ok'));
  assert.equal(await (await hono.request('http://example.test/things/word')).text(),'ok');
  const stream = new Response('svelte', {status:202});
  const event={request:new Request('http://example.test/svelte/123'),route:{id:'/svelte/[id]'}};
  assert.equal(await svelteKitHandle()({event,resolve:()=>stream}),stream);
  assert.equal(await astroMiddleware()({request:new Request('http://example.test/astro/123'),routePattern:'/astro/[id]'},()=>stream),stream);
  await flush();
  const requests=received.filter(e=>e.payload?.kind==='http'&&e.payload.direction==='inbound');
  assert.equal(requests.length,5);
  assert.deepEqual(new Set(requests.map(e=>e.payload.path)),new Set(['/items/:slug','/fail/:slug','/things/:slug','/svelte/[id]','/astro/[id]']));
  assert.equal(received.filter(e=>e.type==='error').length,1);
  assert(!JSON.stringify(received).includes('fixture_secret'));
  shutdown();
  edge.init({publicKey:'pk_fixture',endpoint,persistence:false,component:'worker'});
  const worker = new Hono(); worker.use('*',edgeHono()); worker.get('/worker/:id',c=>c.text('edge'));
  const pending=[];
  assert.equal(await (await worker.fetch(new Request('http://example.test/worker/123'),{}, {waitUntil:p=>pending.push(p),passThroughOnException(){}})).text(),'edge');
  await Promise.all(pending); await edge.flush();
  assert(received.some(e=>e.payload?.path==='/worker/:id'&&e.payload.component==='worker'));
  console.log('PASS: packaged Express, Hono Node/edge, SvelteKit/Astro hook contracts');
} finally {
  shutdown(); server.closeAllConnections(); collector.closeAllConnections();
  await Promise.all([new Promise(r=>server.close(r)),new Promise(r=>collector.close(r))]);
}
